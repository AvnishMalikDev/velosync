/**
 * PM2-backed schedule for jira-md-export (Data Sync Job).
 * Requires `pm2` on PATH (e.g. npm i -g pm2).
 */
const fs = require('fs');
const path = require('path');
const { spawnSync } = require('child_process');

const CONFIG_VERSION = 1;

function getConfigPath(productRoot) {
  return path.join(productRoot, 'data', 'data-sync-job.json');
}

function defaults() {
  return {
    version: CONFIG_VERSION,
    enabled: false,
    pm2ProcessName: 'velosync-data-sync',
    cronExpression: '0 * * * *',
  };
}

function isValidCronExpression(expr) {
  const parts = String(expr || '').trim().split(/\s+/).filter(Boolean);
  return parts.length === 5;
}

function sanitizeProcessName(name) {
  const s = String(name || '')
    .trim()
    .replace(/[^a-zA-Z0-9-_]/g, '');
  return s || defaults().pm2ProcessName;
}

function readConfig(productRoot) {
  const p = getConfigPath(productRoot);
  if (!fs.existsSync(p)) return { ...defaults() };
  try {
    const j = JSON.parse(fs.readFileSync(p, 'utf8'));
    const base = defaults();
    return {
      ...base,
      ...j,
      version: CONFIG_VERSION,
      pm2ProcessName: sanitizeProcessName(j.pm2ProcessName || base.pm2ProcessName),
      cronExpression: String(j.cronExpression || base.cronExpression).trim() || base.cronExpression,
      enabled: !!j.enabled,
    };
  } catch (_) {
    return { ...defaults() };
  }
}

function atomicWriteJson(filePath, data) {
  const dir = path.dirname(filePath);
  fs.mkdirSync(dir, { recursive: true });
  const tmp = path.join(dir, `.data-sync-job.${process.pid}.${Date.now()}.tmp`);
  fs.writeFileSync(tmp, `${JSON.stringify(data, null, 2)}\n`, 'utf8');
  fs.renameSync(tmp, filePath);
}

function writeConfig(productRoot, body) {
  const cur = readConfig(productRoot);
  const cronExpression = String(body?.cronExpression ?? cur.cronExpression).trim();
  if (!isValidCronExpression(cronExpression)) {
    throw new Error('Cron must have 5 fields (e.g. 0 * * * * for hourly). See crontab.guru.');
  }
  const next = {
    version: CONFIG_VERSION,
    enabled: !!body?.enabled,
    pm2ProcessName: sanitizeProcessName(body?.pm2ProcessName ?? cur.pm2ProcessName),
    cronExpression,
  };
  atomicWriteJson(getConfigPath(productRoot), next);
  return next;
}

/** Cached after first successful `pm2 -v` probe (PATH often omits npm global on Windows). */
let cachedPm2Binary = null;

/**
 * resolve a working pm2 binary. On Windows, tries PATH then %APPDATA%\\npm\\pm2.cmd (npm global default).
 */
function tryresolvePm2Binary() {
  if (cachedPm2Binary) return cachedPm2Binary;

  const candidates = [];
  if (process.platform === 'win32') {
    candidates.push('pm2.cmd', 'pm2');
    if (process.env.APPDATA) {
      candidates.push(path.join(process.env.APPDATA, 'npm', 'pm2.cmd'));
    }
  } else {
    candidates.push('pm2');
  }

  for (const bin of candidates) {
    if (bin.includes(path.sep) && !fs.existsSync(bin)) continue;
    const r = spawnSync(bin, ['-v'], {
      encoding: 'utf8',
      maxBuffer: 64 * 1024,
      shell: false,
    });
    if (r.status === 0 && !r.error) {
      cachedPm2Binary = bin;
      return bin;
    }
  }
  return null;
}

function pm2Executable() {
  const resolved = tryresolvePm2Binary();
  return resolved || (process.platform === 'win32' ? 'pm2.cmd' : 'pm2');
}

function runPm2(args, spawnOpts = {}) {
  const opts = {
    encoding: 'utf8',
    maxBuffer: 2 * 1024 * 1024,
    ...spawnOpts,
    shell: false,
  };
  let bin = pm2Executable();
  let r = spawnSync(bin, args, opts);
  if (process.platform === 'win32' && r.error && r.error.code === 'ENOENT' && bin === 'pm2.cmd') {
    r = spawnSync('pm2', args, opts);
  }
  return {
    ok: r.status === 0,
    code: r.status,
    stdout: (r.stdout || '').trim(),
    stderr: (r.stderr || '').trim(),
    error: r.error,
  };
}

function pm2Available() {
  return runPm2(['-v']).ok;
}

function writeEcosystemStub(productRoot, cfg) {
  const name = cfg.pm2ProcessName;
  const outPath = path.join(productRoot, 'ecosystem.data-sync.config.cjs');
  const lines = [
    "'use strict';",
    "const path = require('path');",
    '// Generated by VeloSync Admin (Data Sync Job).',
    '// Portable: paths are relative to this file (keep it in the Product install root, next to server.js).',
    `// From Product root: pm2 start jira-md-export/index.js --name ${JSON.stringify(name)} --cron ${JSON.stringify(cfg.cronExpression)} --no-autorestart`,
    'module.exports = {',
    '  apps: [{',
    `    name: ${JSON.stringify(name)},`,
    "    cwd: path.join(__dirname, 'jira-md-export'),",
    "    script: 'index.js',",
    "    interpreter: 'node',",
    '    autorestart: false,',
    '  }],',
    '};',
    '',
  ];
  fs.writeFileSync(outPath, lines.join('\n'), 'utf8');
  return outPath;
}

/**
 * Register or remove the job in PM2 (cron + one-shot style per APP-SETUP.md).
 */
function applyPm2Schedule(productRoot) {
  const cfg = readConfig(productRoot);
  const jiraDir = path.join(productRoot, 'jira-md-export');
  const indexJs = path.join(jiraDir, 'index.js');
  const name = cfg.pm2ProcessName;

  try {
    writeEcosystemStub(productRoot, cfg);
  } catch (e) {
    console.warn('[data-sync-job] could not write ecosystem stub:', e.message);
  }

  runPm2(['delete', name]);

  if (!cfg.enabled) {
    return {
      ok: true,
      applied: false,
      message: 'Data sync job disabled; removed from PM2 if it existed.',
    };
  }

  if (!fs.existsSync(indexJs)) {
    return { ok: false, message: 'jira-md-export/index.js not found.' };
  }

  // Relative script from Product root so PM2 does not store a machine-specific absolute cwd.
  const r = runPm2(
    [
      'start',
      path.join('jira-md-export', 'index.js'),
      '--name',
      name,
      '--cron',
      cfg.cronExpression,
      '--no-autorestart',
    ],
    { cwd: productRoot },
  );

  if (!r.ok) {
    const hint = !pm2Available()
      ? ' Is PM2 installed globally? (npm i -g pm2)'
      : '';
    return {
      ok: false,
      message: (r.stderr || r.stdout || r.error?.message || `PM2 exited with code ${r.code}`) + hint,
    };
  }

  return {
    ok: true,
    applied: true,
    message: `PM2 job "${name}" scheduled (${cfg.cronExpression}). Check: pm2 list`,
    detail: r.stdout || undefined,
  };
}

/**
 * After .env / projects / connectors change: restart PM2 app so the next run sees new files.
 * If the process is not registered, re-applies schedule when enabled.
 */
function restartDataSyncJob(productRoot, reason) {
  const cfg = readConfig(productRoot);
  if (!cfg.enabled) {
    return { ok: true, skipped: true, message: 'Data sync job disabled; no PM2 restart.' };
  }
  if (!pm2Available()) {
    return {
      ok: false,
      skipped: true,
      message: 'PM2 not found on PATH; install with npm i -g pm2 (optional).',
    };
  }

  const name = cfg.pm2ProcessName;
  const rRestart = runPm2(['restart', name, '--update-env']);
  if (rRestart.ok) {
    if (reason) console.log('[data-sync-job] PM2 restart (' + reason + '):', rRestart.stdout || 'ok');
    return {
      ok: true,
      skipped: false,
      message: rRestart.stdout || `PM2 restarted "${name}" with updated environment.`,
    };
  }

  const apply = applyPm2Schedule(productRoot);
  if (apply.ok) {
    if (reason) console.log('[data-sync-job] PM2 re-applied after restart failed (' + reason + ')');
    return {
      ok: true,
      skipped: false,
      message:
        apply.message ||
        `PM2 re-registered "${name}". (Restart was not possible — process may not have been running.)`,
    };
  }

  return {
    ok: false,
    skipped: false,
    message:
      (rRestart.stderr || rRestart.stdout || 'Restart failed.') +
      ' Open Admin ? Data Sync Job and click Apply to PM2.',
  };
}

module.exports = {
  defaults,
  readConfig,
  writeConfig,
  runPm2,
  pm2Executable,
  pm2Available,
  applyPm2Schedule,
  restartDataSyncJob,
  isValidCronExpression,
  getConfigPath,
};
